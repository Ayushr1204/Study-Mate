import { useState } from 'react'
import { Link } from 'react-router-dom'
import { Play } from 'lucide-react'
import { GraphLegend, GraphView } from '../components/GraphView'
import { RunPanel } from '../components/RunPanel'
import { Button, Card, Chip, ErrorBanner, Page, PageHeader } from '../components/ui'
import { inputClass } from '../components/styles'
import { useApp } from '../context/app-context'
import { useAsync } from '../hooks/useAsync'
import { nodeLabel } from '../lib/format'
import { api } from '../services/api'
import type { Execution } from '../types'

export function GraphExplorerPage() {
  const { userId } = useApp()
  const graph = useAsync(() => api.graph(), [])
  const latest = useAsync(() => api.latestExecution(), [userId])
  const [run, setRun] = useState<{ execution: Execution; threadId: string } | null>(null)
  const [selected, setSelected] = useState<string | null>(null)
  const [prompt, setPrompt] = useState('')
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState<unknown>(null)

  const g = graph.data
  const execution = run?.execution ?? latest.data?.execution ?? null
  const node = g?.nodes.find((n) => n.id === selected) ?? null

  const submit = async () => {
    setBusy(true)
    setError(null)
    try {
      const res = await api.chat(null, prompt.trim())
      setRun({ execution: res.execution, threadId: res.thread_id })
      setPrompt('')
    } catch (e) {
      setError(e)
    } finally {
      setBusy(false)
    }
  }

  return (
    <Page wide>
      <PageHeader title="Graph Explorer" description="The structure below is read from the compiled LangGraph (get_graph), not drawn by hand. Run a message through it to highlight the path it took." />
      {graph.error && <ErrorBanner error={graph.error} onRetry={graph.reload} className="mb-4" />}
      {g && (
        <div className="grid gap-6 xl:grid-cols-[1fr_340px]">
          <div className="space-y-6">
            <Card title={g.name} action={<GraphLegend />}>
              <GraphView graph={g} execution={execution} selected={selected} onSelect={setSelected} />
            </Card>

            <Card title="Run a message through the graph" description="Creates a new conversation and executes the real workflow.">
              <form className="flex flex-col gap-2 sm:flex-row" onSubmit={(e) => { e.preventDefault(); if (prompt.trim()) void submit() }}>
                <input className={inputClass} aria-label="Message" value={prompt} onChange={(e) => setPrompt(e.target.value)} placeholder="e.g. Explain CPU scheduling  ·  Quiz me on deadlocks  ·  Summarize: …" />
                <Button type="submit" variant="primary" loading={busy} disabled={!prompt.trim()}><Play className="size-4" /> Run</Button>
              </form>
              {!!error && <ErrorBanner error={error} className="mt-3" />}
              {run && <p className="mt-2 text-xs text-muted">Saved as a conversation: <Link className="text-accent hover:underline" to={`/chat/${run.threadId}`}>open in Study Chat</Link></p>}
            </Card>

            <div className="grid gap-6 lg:grid-cols-2">
              <Card title="State reducers" description="How concurrent/sequential writes to a state key are merged">
                <dl className="space-y-3 text-sm">
                  {Object.entries(g.reducers).map(([key, r]) => (
                    <div key={key}><dt className="font-mono text-xs text-accent">{key} <span className="text-faint">· {r.reducer}</span></dt><dd className="mt-0.5 text-muted">{r.behaviour}</dd></div>
                  ))}
                </dl>
              </Card>
              <Card title="State fields">
                <div className="flex flex-wrap gap-1.5">{g.state_fields.map((f) => <Chip key={f}><span className="font-mono">{f}</span></Chip>)}</div>
                <p className="mt-4 mb-1.5 text-xs font-medium text-muted">Router intents</p>
                <div className="flex flex-wrap gap-1.5">{g.intents.map((i) => <Chip key={i} tone="warn">{i}</Chip>)}</div>
              </Card>
            </div>

            <Card title="Mermaid source" description="Generated by the compiled graph (draw_mermaid)">
              <pre className="max-h-80 overflow-auto rounded-md bg-canvas p-3 font-mono text-xs leading-relaxed text-muted">{g.mermaid}</pre>
            </Card>
          </div>

          <aside className="space-y-6">
            <Card title={node ? (node.title ?? nodeLabel(node.id)) : 'Node inspector'}>
              {!node && <p className="text-sm text-muted">Select a node in the graph to see what it reads and writes.</p>}
              {node && (
                <div className="space-y-3 text-sm">
                  <p className="font-mono text-xs text-faint">{node.id}</p>
                  {node.description && <p className="text-muted">{node.description}</p>}
                  {node.reads && node.reads.length > 0 && <div><p className="mb-1 text-xs font-medium text-muted">Reads</p><div className="flex flex-wrap gap-1.5">{node.reads.map((r) => <Chip key={r}><span className="font-mono">{r}</span></Chip>)}</div></div>}
                  {node.writes && node.writes.length > 0 && <div><p className="mb-1 text-xs font-medium text-muted">Writes</p><div className="flex flex-wrap gap-1.5">{node.writes.map((r) => <Chip key={r} tone="accent"><span className="font-mono">{r}</span></Chip>)}</div></div>}
                  <div>
                    <p className="mb-1 text-xs font-medium text-muted">Edges</p>
                    <ul className="space-y-1 font-mono text-xs">
                      {g.edges.filter((e) => e.source === node.id || e.target === node.id).map((e, i) => (
                        <li key={i} className="text-muted">{nodeLabel(e.source)} → {nodeLabel(e.target)}{e.conditional && <span className="text-warn"> (conditional{e.label ? `: ${e.label}` : ''})</span>}</li>
                      ))}
                    </ul>
                  </div>
                </div>
              )}
            </Card>
            <Card title={run ? 'This run' : 'Latest run'}>
              <RunPanel execution={execution} />
            </Card>
          </aside>
        </div>
      )}
    </Page>
  )
}
