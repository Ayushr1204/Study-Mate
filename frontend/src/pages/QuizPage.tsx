import { useState } from 'react'
import { CheckCircle2, ListChecks, RotateCcw, Trophy, XCircle } from 'lucide-react'
import { Button, Card, Chip, EmptyState, ErrorBanner, Label, Page, PageHeader, Segmented } from '../components/ui'
import { cx, inputClass } from '../components/styles'
import { useApp } from '../context/app-context'
import { useAsync } from '../hooks/useAsync'
import { relativeTime } from '../lib/format'
import { api } from '../services/api'
import type { QuizResponse, QuizResult } from '../types'

const LETTERS = ['A', 'B', 'C', 'D']
const DIFFICULTIES = [
  { value: 'easy', label: 'Easy' },
  { value: 'medium', label: 'Medium' },
  { value: 'hard', label: 'Hard' },
]

function Setup({ onCreated, busy, setBusy }: { onCreated: (q: QuizResponse) => void; busy: boolean; setBusy: (b: boolean) => void }) {
  const [topic, setTopic] = useState('')
  const [difficulty, setDifficulty] = useState('medium')
  const [count, setCount] = useState(5)
  const [error, setError] = useState<unknown>(null)

  const submit = async () => {
    setBusy(true)
    setError(null)
    try {
      onCreated(await api.generateQuiz(topic.trim(), difficulty, count))
    } catch (e) {
      setError(e)
    } finally {
      setBusy(false)
    }
  }

  return (
    <Card title="New quiz" description="Questions are generated by the quiz_node of the LangGraph workflow.">
      <form
        className="space-y-4"
        onSubmit={(e) => {
          e.preventDefault()
          void submit()
        }}
      >
        <div>
          <Label htmlFor="quiz-topic">Subject or topic</Label>
          <input id="quiz-topic" className={inputClass} value={topic} maxLength={120} onChange={(e) => setTopic(e.target.value)} placeholder="e.g. Deadlock in operating systems" autoFocus />
        </div>
        <div className="flex flex-wrap gap-6">
          <div>
            <Label>Difficulty</Label>
            <Segmented label="Difficulty" options={DIFFICULTIES} value={difficulty} onChange={setDifficulty} />
          </div>
          <div>
            <Label htmlFor="quiz-count">Number of questions</Label>
            <select id="quiz-count" value={count} onChange={(e) => setCount(Number(e.target.value))} className={cx(inputClass, 'w-28')}>
              {[3, 4, 5, 7, 10, 15].map((n) => <option key={n} value={n}>{n}</option>)}
            </select>
          </div>
        </div>
        {!!error && <ErrorBanner error={error} />}
        <Button type="submit" variant="primary" loading={busy} disabled={topic.trim().length < 2}>
          {busy ? 'Generating…' : 'Generate quiz'}
        </Button>
      </form>
    </Card>
  )
}

function Taking({ quiz, onResult, onDiscard }: { quiz: QuizResponse; onResult: (r: QuizResult, answers: (number | null)[]) => void; onDiscard: () => void }) {
  const [answers, setAnswers] = useState<(number | null)[]>(() => quiz.questions.map(() => null))
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState<unknown>(null)
  const answered = answers.filter((a) => a !== null).length

  const submit = async () => {
    setBusy(true)
    setError(null)
    try {
      onResult(await api.submitQuiz(quiz.quiz_id, answers), answers)
    } catch (e) {
      setError(e)
    } finally {
      setBusy(false)
    }
  }

  return (
    <div className="space-y-4">
      <Card
        title={quiz.topic}
        description={`${quiz.difficulty} · ${quiz.questions.length} questions · ${answered}/${quiz.questions.length} answered`}
        action={<Button size="sm" variant="ghost" onClick={onDiscard}>Discard</Button>}
      >
        <p className="text-xs text-faint">
          Generated in {quiz.execution.duration_ms} ms via <span className="font-mono">{quiz.execution.path.join(' → ')}</span>
          {quiz.execution.llm.provider && <> · {quiz.execution.llm.provider}</>}
        </p>
        {quiz.warnings.map((w) => <p key={w} className="mt-2 rounded-md border border-warn/30 bg-warn/10 px-3 py-2 text-xs text-warn">{w}</p>)}
      </Card>

      {quiz.questions.map((q, qi) => (
        <Card key={qi}>
          <fieldset>
            <legend className="mb-3 text-sm font-medium"><span className="mr-2 text-faint">{qi + 1}.</span>{q.question}</legend>
            <div className="space-y-2">
              {q.options.map((opt, oi) => {
                const checked = answers[qi] === oi
                return (
                  <label key={oi} className={cx('flex cursor-pointer items-start gap-3 rounded-md border px-3 py-2.5 text-sm transition-colors', checked ? 'border-accent bg-accent-soft' : 'border-line hover:bg-hover')}>
                    <input type="radio" name={`q${qi}`} className="sr-only" checked={checked} onChange={() => setAnswers((a) => a.map((v, i) => (i === qi ? oi : v)))} />
                    <span className={cx('mt-px flex size-5 shrink-0 items-center justify-center rounded border text-[11px] font-medium', checked ? 'border-accent bg-accent text-accent-fg' : 'border-line-strong text-muted')}>{LETTERS[oi]}</span>
                    <span>{opt}</span>
                  </label>
                )
              })}
            </div>
          </fieldset>
        </Card>
      ))}

      {!!error && <ErrorBanner error={error} />}
      <div className="flex items-center gap-3">
        <Button variant="primary" onClick={() => void submit()} loading={busy}>Submit answers</Button>
        {answered < quiz.questions.length && <span className="text-xs text-muted">{quiz.questions.length - answered} unanswered will count as skipped.</span>}
      </div>
    </div>
  )
}

function Results({ result, onRetry, onNew }: { result: QuizResult; onRetry: () => void; onNew: () => void }) {
  const tone = result.percent >= 80 ? 'text-ok' : result.percent >= 50 ? 'text-warn' : 'text-danger'
  return (
    <div className="space-y-4">
      <Card>
        <div className="flex flex-wrap items-center justify-between gap-4">
          <div className="flex items-center gap-4">
            <Trophy className={cx('size-8', tone)} aria-hidden />
            <div>
              <p className="text-xs text-muted">{result.topic}</p>
              <p className="text-3xl font-semibold tabular-nums" aria-label={`Score ${result.score} out of ${result.total}`}>
                <span className={tone}>{result.score}</span><span className="text-faint"> / {result.total}</span>
                <span className="ml-3 text-base text-muted">{result.percent}%</span>
              </p>
            </div>
          </div>
          <div className="flex gap-2">
            <Button onClick={onRetry}><RotateCcw className="size-4" /> Retake</Button>
            <Button variant="primary" onClick={onNew}>New quiz</Button>
          </div>
        </div>
        {result.needs_revision && (
          <p className="mt-3 rounded-md border border-warn/30 bg-warn/10 px-3 py-2 text-xs text-warn">
            Below 70%: “{result.topic}” was added to <em>Needs revision</em> in your long-term learning profile.
          </p>
        )}
      </Card>

      {result.results.map((r, i) => (
        <Card key={i}>
          <div className="mb-3 flex items-start gap-2">
            {r.is_correct ? <CheckCircle2 className="mt-0.5 size-4 shrink-0 text-ok" aria-label="Correct" /> : <XCircle className="mt-0.5 size-4 shrink-0 text-danger" aria-label="Incorrect" />}
            <p className="text-sm font-medium"><span className="mr-2 text-faint">{i + 1}.</span>{r.question}</p>
          </div>
          <ul className="space-y-1.5">
            {r.options.map((opt, oi) => {
              const isCorrect = oi === r.correct
              const isSelected = oi === r.selected
              return (
                <li key={oi} className={cx('flex items-start gap-3 rounded-md border px-3 py-2 text-sm', isCorrect ? 'border-ok/50 bg-ok/10' : isSelected ? 'border-danger/50 bg-danger/10' : 'border-line opacity-70')}>
                  <span className="mt-px flex size-5 shrink-0 items-center justify-center rounded border border-line-strong text-[11px] text-muted">{LETTERS[oi]}</span>
                  <span className="flex-1">{opt}</span>
                  {isCorrect && <Chip tone="ok">correct answer</Chip>}
                  {isSelected && !isCorrect && <Chip tone="danger">your answer</Chip>}
                </li>
              )
            })}
          </ul>
          {r.selected === null && <p className="mt-2 text-xs text-muted">You skipped this question.</p>}
          {r.explanation && <p className="mt-3 border-t border-line pt-3 text-sm text-muted"><span className="font-medium text-fg">Explanation. </span>{r.explanation}</p>}
        </Card>
      ))}
    </div>
  )
}

export function QuizPage() {
  const { userId } = useApp()
  const history = useAsync(() => api.quizzes(), [userId])
  const [busy, setBusy] = useState(false)
  const [quiz, setQuiz] = useState<QuizResponse | null>(null)
  const [result, setResult] = useState<QuizResult | null>(null)
  const [attempt, setAttempt] = useState(0)

  return (
    <Page>
      <PageHeader title="Quiz Generator" description="Generate multiple-choice quizzes with the LangGraph quiz node, answer them, and see explanations and your score. Weak topics are saved to your learning profile." />
      <div className="grid gap-6 lg:grid-cols-[1fr_300px]">
        <div>
          {!quiz && <Setup busy={busy} setBusy={setBusy} onCreated={(q) => { setQuiz(q); setResult(null); history.reload() }} />}
          {quiz && !result && <Taking key={`${quiz.quiz_id}-${attempt}`} quiz={quiz} onDiscard={() => setQuiz(null)} onResult={(r) => { setResult(r); history.reload() }} />}
          {quiz && result && <Results result={result} onRetry={() => { setResult(null); setAttempt((n) => n + 1) }} onNew={() => { setQuiz(null); setResult(null) }} />}
        </div>
        <Card title="Quiz history" padded={false}>
          {history.data?.length === 0 && <EmptyState icon={<ListChecks className="size-6" />} title="No quizzes yet">Generate your first quiz to start tracking scores.</EmptyState>}
          <ul className="divide-y divide-line">
            {history.data?.map((q) => (
              <li key={q.id} className="px-4 py-2.5">
                <p className="truncate text-sm">{q.topic}</p>
                <p className="mt-0.5 flex flex-wrap items-center gap-1.5 text-[11px] text-faint">
                  <span className="capitalize">{q.difficulty}</span> · {q.num_questions} q · {relativeTime(q.created_at)}
                  {q.attempts > 0 ? <Chip tone="accent">best {q.best_score}/{q.num_questions}</Chip> : <Chip>not attempted</Chip>}
                </p>
              </li>
            ))}
          </ul>
          {history.error && <div className="p-3"><ErrorBanner error={history.error} onRetry={history.reload} /></div>}
        </Card>
      </div>
    </Page>
  )
}
